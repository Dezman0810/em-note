  function nodeHasSummary(node) {
    if (!node) return false;
    try {
      if (typeof node.checkHasGeneralization === 'function') {
        return !!node.checkHasGeneralization();
      }
    } catch (e) {}
    try {
      if (typeof node.getData === 'function') {
        var g = node.getData('generalization');
        if (Array.isArray(g)) return g.length > 0;
        return !!(g && (g.text || g.richText));
      }
    } catch (e2) {}
    return false;
  }

  function activeHasSummary(mindMap) {
    var list =
      (mindMap && mindMap.renderer && mindMap.renderer.activeNodeList) || [];
    for (var i = 0; i < list.length; i++) {
      if (nodeHasSummary(list[i])) return true;
    }
    return false;
  }

  function wrapFn(obj, key, fn) {
    if (!obj || typeof obj[key] !== 'function' || obj[key].__smmWrapped) return;
    var orig = obj[key].bind(obj);
    var wrapped = function () {
      return fn(orig, arguments);
    };
    wrapped.__smmWrapped = true;
    obj[key] = wrapped;
  }

  function wrapSummaryToggle(mindMap, bus) {
    function intercept(orig, args) {
      var name = args[0];
      if (name === 'ADD_GENERALIZATION' && activeHasSummary(mindMap)) {
        return orig('REMOVE_GENERALIZATION');
      }
      if (name === 'ADD_GENERALIZATION') {
        var rest = Array.prototype.slice.call(args, 1);
        if (!rest.length || rest[0] == null) {
          rest[0] = { text: getUiLang() === 'ru' ? 'Сводка' : 'Summary' };
        } else if (typeof rest[0] === 'object' && rest[0] && !rest[0].text) {
          rest[0].text = getUiLang() === 'ru' ? 'Сводка' : 'Summary';
        }
        return orig.apply(null, [name].concat(rest));
      }
      return orig.apply(null, Array.prototype.slice.call(args));
    }
    wrapFn(mindMap, 'execCommand', intercept);
    if (mindMap && mindMap.command) wrapFn(mindMap.command, 'exec', intercept);
    if (bus && !bus.__smmSummaryToggle && typeof bus.$emit === 'function') {
      bus.__smmSummaryToggle = true;
      var emit = bus.$emit.bind(bus);
      bus.$emit = function (evt, cmd) {
        if (
          evt === 'execCommand' &&
          cmd === 'ADD_GENERALIZATION' &&
          mindMap &&
          activeHasSummary(mindMap)
        ) {
          return emit('execCommand', 'REMOVE_GENERALIZATION');
        }
        return emit.apply(bus, arguments);
      };
    }
  }

  function forceStandardMargins(mindMap) {
    if (!mindMap || typeof mindMap.setThemeConfig !== 'function') return;
    var name = mindMap.getTheme && mindMap.getTheme();
    if (name !== 'default') return;
    var custom = {};
    try {
      custom = mindMap.getCustomThemeConfig() || {};
    } catch (e) {}
    var second = Object.assign({}, custom.second || {}, { marginX: 50, marginY: 15 });
    var node = Object.assign({}, custom.node || {}, { marginX: 30, marginY: 5 });
    mindMap.setThemeConfig(Object.assign({}, custom, { second: second, node: node }), true);
  }

  function patchDefaultThemeMargins(mindMap) {
    if (!mindMap) return;
    var maps = [];
    if (mindMap.themeMap) maps.push(mindMap.themeMap);
    var ctor = mindMap.constructor;
    if (ctor && ctor.themeMap) maps.push(ctor.themeMap);
    maps.forEach(function (map) {
      var th = map.default;
      if (!th) return;
      if (th.second) th.second.marginY = 15;
      if (th.node) th.node.marginY = 5;
    });
    wrapFn(mindMap, 'setTheme', function (orig, args) {
      var result = orig.apply(null, Array.prototype.slice.call(args));
      forceStandardMargins(mindMap);
      return result;
    });
    forceStandardMargins(mindMap);
  }

